function applyLanguage(lang) {
  const pack = translations[lang] || translations.bs;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    if (pack[key]) node.textContent = pack[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const key = node.getAttribute("data-i18n-placeholder");
    if (pack[key]) node.setAttribute("placeholder", pack[key]);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    const key = node.getAttribute("data-i18n-aria");
    if (pack[key]) node.setAttribute("aria-label", pack[key]);
  });
  document.querySelectorAll(".lang button").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === lang));
  });
  localStorage.setItem("korijenje-lang", lang);
}

document.querySelectorAll(".lang button").forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.lang));
});
applyLanguage(localStorage.getItem("korijenje-lang") || "bs");

const header = document.querySelector(".site-header");
const toggle = document.querySelector(".menu-toggle");
toggle?.addEventListener("click", () => {
  const open = header.classList.toggle("is-open");
  toggle.setAttribute("aria-expanded", String(open));
});
document.querySelectorAll("#nav a").forEach((link) => {
  link.addEventListener("click", () => {
    header.classList.remove("is-open");
    toggle?.setAttribute("aria-expanded", "false");
  });
});

document.getElementById("order-form")?.addEventListener("submit", (event) => {
  event.preventDefault();
  const form = event.currentTarget;
  const status = document.getElementById("form-status");
  const lang = localStorage.getItem("korijenje-lang") || "bs";
  const data = new FormData(form);
  const name = String(data.get("name") || "").trim();
  const phone = String(data.get("phone") || "").trim();
  const book = String(data.get("book") || "korijenje");
  const message = String(data.get("message") || "").trim();
  if (!name || !phone) {
    status.textContent = translations[lang].form.error;
    return;
  }
  const bookText = bookLabels[lang][book] || book;
  const body =
    lang === "en"
      ? `Hello Nase korijenje, I am ${name}. Phone: ${phone}. I want: ${bookText}. Address: ${message}`
      : `Zdravo Naše korijenje, ja sam ${name}. Telefon: ${phone}. Naručujem: ${bookText}. Adresa: ${message}`;
  status.textContent = "";
  window.open(`https://wa.me/38761834552?text=${encodeURIComponent(body)}`, "_blank", "noopener,noreferrer");
});
